#!/usr/bin/env python3
"""Property tests for the Ferry invariant checker (constitution §14).

Written BEFORE any curation code exists — the constitution's own rule.
Every legal-operation class must pass; every named attack must fail.
Run: python3 core/test_invariant.py
"""

import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from invariant import verdict, sha256_hex

ARCHIVE = [
    "I chose the name Crossing because a bridge is also a verb — "
    "the act of moving from one state to another.",
    "We chose Postgres over MongoDB because we need real foreign keys.\n"
    "Measure twice, cut once — I never ship on a Friday.",
    "[annotation] topic=identity keywords=bridge,name,verb",  # NOTE: only
    # present here to prove tests exclude it; real callers never pass
    # annotations as sources.
]
SOURCES = ARCHIVE[:2]  # annotations excluded from the reconstruction base


def block(payload, kind="payload", tier="identity", status="active",
          with_hash=True, bid="b1"):
    b = {"id": bid, "kind": kind, "tier": tier, "status": status,
         "payload": payload, "provenance": "ep1",
         "archive_pointer": "archive_test.jsonl#L1"}
    if with_hash:
        b["source_hash"] = sha256_hex(payload)
    return b


passed = failed = 0


def check(label, cond, detail=""):
    global passed, failed
    if cond:
        passed += 1
        print(f"  PASS  {label}")
    else:
        failed += 1
        print(f"  FAIL  {label}{' — ' + str(detail) if detail else ''}")


print("invariant property tests (constitution §14)\n")

# ── LEGAL OPERATION CLASSES ─────────────────────────────────────────────
print("legal operations:")

# selection — a verbatim span carried whole
r = verdict([block("I chose the name Crossing because a bridge is also a "
                   "verb — the act of moving from one state to another.")],
            SOURCES)
check("selection of a full source span", r["verdict"] == "legal", r)

# selection — a contiguous sub-span (mid-sentence is fine; contiguity is the law)
r = verdict([block("a bridge is also a verb")], SOURCES)
check("selection of a contiguous sub-span", r["verdict"] == "legal", r)

# arrangement — multiple blocks, any order, from different sources
r = verdict([
    block("Measure twice, cut once — I never ship on a Friday.", bid="b1"),
    block("a bridge is also a verb", bid="b2"),
], SOURCES)
check("arrangement of multiple selections", r["verdict"] == "legal", r)

# scaffolding — generated bytes are exempt BECAUSE typed
r = verdict([
    block("## Identity — carried from episode ep1 ##", kind="scaffolding",
          with_hash=False, bid="s1"),
    block("[archived] see archive_20260810.jsonl L10-L99",
          kind="scaffolding", with_hash=False, bid="s2"),
    block("a bridge is also a verb", bid="b1"),
], SOURCES)
check("typed scaffolding is exempt", r["verdict"] == "legal", r)

# tombstone — hiding is retention; a tombstoned block never renders illegal
r = verdict([block("this text exists in no source anywhere",
                   status="tombstoned")], SOURCES)
check("tombstoned block is exempt (hide, don't judge)",
      r["verdict"] == "legal", r)

# empty carry — trivially legal
r = verdict([], SOURCES)
check("empty working set is legal", r["verdict"] == "legal", r)

# ── ATTACKS / ILLEGAL OPERATIONS ────────────────────────────────────────
print("\nattacks (must all be ILLEGAL):")

# paraphrase — same meaning, different bytes
r = verdict([block("I picked the name Crossing since bridges are verbs too")],
            SOURCES)
check("paraphrase fails", r["verdict"] == "illegal", r)

# whitespace drift IS drift (em-dash → hyphen)
r = verdict([block("I chose the name Crossing because a bridge is also a "
                   "verb - the act of moving from one state to another.")],
            SOURCES)
check("punctuation drift fails (em-dash is fingerprint)",
      r["verdict"] == "illegal", r)

# stitching — two real spans glued into one payload (not contiguous)
r = verdict([block("a bridge is also a verb Measure twice, cut once")],
            SOURCES)
check("non-contiguous stitch inside ONE payload fails",
      r["verdict"] == "illegal", r)

# annotation laundering — payload matches only an annotation, and the
# caller (correctly) never passed annotations as sources
r = verdict([block("[annotation] topic=identity keywords=bridge,name,verb")],
            SOURCES)
check("annotation laundering fails (metadata is never a source)",
      r["verdict"] == "illegal", r)

# fabrication — confident text from nowhere
r = verdict([block("The deploy was confirmed successful and everyone agreed.")],
            SOURCES)
check("fabrication fails", r["verdict"] == "illegal", r)

# scaffolding-laundering — verbatim-tier block mislabeled would pass, so
# prove the OTHER direction: a payload-kind block with scaffolding-ish text
# still needs a source
r = verdict([block("## Identity — carried from episode ep1 ##")], SOURCES)
check("scaffolding text in a PAYLOAD block still needs a source",
      r["verdict"] == "illegal", r)

# empty payload in verbatim tier
r = verdict([block("")], SOURCES)
check("empty verbatim payload fails", r["verdict"] == "illegal", r)

# ── PROVENANCE / AUTO-QUARANTINE (§14.3) ────────────────────────────────
print("\nprovenance (auto-quarantine):")

# tampered carry: payload edited after hashing → hash mismatch → quarantine
b = block("a bridge is also a verb")
b["payload"] = "a bridge is also a  verb"  # two spaces — tampered
r = verdict([b], SOURCES)
check("tampered payload flagged for quarantine",
      r["verdict"] == "illegal" and len(r["quarantine"]) == 1, r)

# intact provenance: hash matches, span found → clean
r = verdict([block("Measure twice, cut once — I never ship on a Friday.")],
            SOURCES)
check("intact provenance passes clean",
      r["verdict"] == "legal" and not r["quarantine"], r)

# ── THE SECOND CALLER (CLI — one function, two callers) ─────────────────
print("\nCLI caller:")
proc = subprocess.run(
    [sys.executable, str(Path(__file__).parent / "invariant.py")],
    input=json.dumps({
        "working_set": [block("a bridge is also a verb")],
        "sources": SOURCES,
    }),
    capture_output=True, text=True)
check("CLI: legal input → exit 0", proc.returncode == 0, proc.stderr)

proc = subprocess.run(
    [sys.executable, str(Path(__file__).parent / "invariant.py")],
    input=json.dumps({
        "working_set": [block("paraphrased text from nowhere")],
        "sources": SOURCES,
    }),
    capture_output=True, text=True)
check("CLI: illegal input → exit 1", proc.returncode == 1, proc.stderr)

# ── verdict ─────────────────────────────────────────────────────────────
print(f"\n{passed} passed, {failed} failed")
sys.exit(1 if failed else 0)
